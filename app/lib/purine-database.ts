/**
 * Search foods by name query, optionally filtering by category and/or purine level.
 */
export function searchFoods(
  query: string,
  category?: string,
  level?: string,
): PurineFood[] {
  const lowerQuery = query.toLowerCase().trim();

  return PURINE_DATABASE.filter((food) => {
    const matchesQuery = lowerQuery === '' || food.name.toLowerCase().includes(lowerQuery);
    const matchesCategory = !category || food.category === category;
    const matchesLevel = !level || food.purineLevel === level;
    return matchesQuery && matchesCategory && matchesLevel;
  });
}

/**
 * Get all foods belonging to a specific category.
 */
export function getFoodsByCategory(category: string): PurineFood[] {
  return PURINE_DATABASE.filter((food) => food.category === category);
}

/**
 * Get all foods at a specific purine level.
 */
export function getFoodsByLevel(level: string): PurineFood[] {
  return PURINE_DATABASE.filter((food) => food.purineLevel === level);
}
