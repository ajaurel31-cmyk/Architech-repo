// ---------------------------------------------------------------------------
// Helper: determine purine level from mg value
// ---------------------------------------------------------------------------

export function getPurineLevel(mg: number): 'low' | 'moderate' | 'high' | 'very_high' {
  if (mg <= 100) return 'low';
  if (mg <= 200) return 'moderate';
  if (mg <= 300) return 'high';
  return 'very_high';
}

